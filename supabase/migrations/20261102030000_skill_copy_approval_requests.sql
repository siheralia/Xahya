-- Copying a skill now requires an explicit management approval.
-- No existing skill copies are changed.
CREATE TABLE public."skillCopyRequest" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "characterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "copierSkillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  "sourceSkillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  mode text NOT NULL CHECK (mode IN ('PERMANENT','TEMPORARY','IMITATION','COLLECTION')),
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  "copiedSkillId" integer REFERENCES public."skill"(id) ON DELETE SET NULL,
  "imitationPayload" jsonb,
  "reviewedByUserId" integer REFERENCES public."user"(id) ON DELETE SET NULL,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "reviewedAt" timestamptz
);
CREATE UNIQUE INDEX skill_copy_request_one_pending
  ON public."skillCopyRequest" ("characterId","copierSkillId","sourceSkillId",mode)
  WHERE status='PENDING';
CREATE INDEX skill_copy_request_status_recent ON public."skillCopyRequest" (status,id DESC);
CREATE INDEX skill_copy_request_character_recent ON public."skillCopyRequest" ("characterId",id DESC);
ALTER TABLE public."skillCopyRequest" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public."skillCopyRequest" FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public."skillCopyRequest_id_seq" FROM anon,authenticated;
