-- Temporary thefts suppress the original only while the theft is active.
-- The original skill's status never changes; expiry restores its availability.
CREATE TABLE IF NOT EXISTS public."skillTheft" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "thiefCharacterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "victimCharacterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "stealingSkillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  "sourceSkillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  "stolenSkillId" integer NOT NULL UNIQUE REFERENCES public."skill"(id) ON DELETE CASCADE,
  "remainingTurns" integer NOT NULL CHECK ("remainingTurns" >= 0),
  status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','EXPIRED')),
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "expiredAt" timestamptz
);
CREATE UNIQUE INDEX IF NOT EXISTS skill_theft_one_active_victim_skill
  ON public."skillTheft" ("sourceSkillId") WHERE status='ACTIVE';
CREATE INDEX IF NOT EXISTS skill_theft_thief_status
  ON public."skillTheft" ("thiefCharacterId",status);
CREATE INDEX IF NOT EXISTS skill_theft_victim_status
  ON public."skillTheft" ("victimCharacterId",status);
ALTER TABLE public."skillTheft" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public."skillTheft" FROM anon,authenticated;
REVOKE ALL ON SEQUENCE public."skillTheft_id_seq" FROM anon,authenticated;

-- A failed opposed roll cannot be spammed until it succeeds.
-- Server claims one attempt per thief + target skill every 60 seconds.
CREATE TABLE IF NOT EXISTS public."skillTheftAttemptGuard" (
  "thiefCharacterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "sourceSkillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  "nextAllowedAt" timestamptz NOT NULL,
  PRIMARY KEY ("thiefCharacterId","sourceSkillId")
);
ALTER TABLE public."skillTheftAttemptGuard" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public."skillTheftAttemptGuard" FROM anon,authenticated;
