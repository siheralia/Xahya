-- New improvement-credit currency and copy/upgrade records.
ALTER TABLE public."character" ADD COLUMN IF NOT EXISTS "skillUpgradeCredits" integer NOT NULL DEFAULT 0;
ALTER TABLE public."character" ADD CONSTRAINT character_skill_upgrade_credits_nonnegative CHECK ("skillUpgradeCredits" >= 0);

CREATE TABLE IF NOT EXISTS public."skillUpgradeRequest" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "characterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "skillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  "baselinePch" integer NOT NULL CHECK ("baselinePch" >= 0),
  "nextPch" integer NOT NULL CHECK ("nextPch" > 0),
  "deltaPch" integer NOT NULL CHECK ("deltaPch" > 0),
  payload jsonb NOT NULL,
  status text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING','APPROVED','REJECTED')),
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS skill_upgrade_one_pending_idx ON public."skillUpgradeRequest" ("skillId") WHERE status='PENDING';
CREATE INDEX IF NOT EXISTS skill_upgrade_character_idx ON public."skillUpgradeRequest" ("characterId",status);

CREATE TABLE IF NOT EXISTS public."skillCopy" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "characterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "copierSkillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  "sourceSkillId" integer NOT NULL REFERENCES public."skill"(id) ON DELETE CASCADE,
  "copiedSkillId" integer NOT NULL UNIQUE REFERENCES public."skill"(id) ON DELETE CASCADE,
  mode text NOT NULL CHECK (mode IN ('PERMANENT','TEMPORARY','COLLECTION')),
  "remainingTurns" integer CHECK ("remainingTurns" IS NULL OR "remainingTurns" >= 0),
  equipped boolean NOT NULL DEFAULT true,
  "createdAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS skill_copy_character_idx ON public."skillCopy" ("characterId",mode);
CREATE UNIQUE INDEX IF NOT EXISTS skill_copy_distinct_source_idx ON public."skillCopy" ("characterId","copierSkillId","sourceSkillId",mode);

ALTER TABLE public."skillUpgradeRequest" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."skillCopy" ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public."skillUpgradeRequest",public."skillCopy" FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public."skillUpgradeRequest_id_seq",public."skillCopy_id_seq" FROM anon,authenticated;

