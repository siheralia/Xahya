create table if not exists public."characterStatValue" (
  id integer generated by default as identity primary key,
  "characterId" integer not null references public."character"(id) on delete cascade,
  "statKey" text not null,
  value integer not null default 0,
  constraint "characterStatValue_characterId_statKey_key" unique ("characterId", "statKey"),
  constraint "characterStatValue_statKey_nonempty_check" check (length(trim("statKey")) > 0)
);

alter table public."characterStatValue" enable row level security;
