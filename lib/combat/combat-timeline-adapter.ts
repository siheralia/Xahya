/**
 * Server-facing bridge from Xahya's existing combat commands to v2 temporal
 * reservations. This is an intention compiler, never a damage or resource
 * resolver. The trusted server still validates targets, equipment, skills,
 * mana, inventory and permissions before committing a combat action.
 */
import {
  actionPoints,defaultAttackSource,effectiveCombatSpeed,turnTicks,weaponForSource,
  type CombatCommand,type CombatFighter,type CombatState,type PhysicalAttackSource,type Side,
} from "./turn-engine.ts";
import type {CombatSkillPlan} from "./skill-casting.ts";
import {offhandArmorShield} from "../items/combat-wearables.ts";
import {fieldPosition,validatePlanarMove} from "./field-plane.ts";
import {physicalProjectileFlightTicks} from "./timeline-projectile-flight.ts";
import {
  newContinuousCombatTimeline,queueTimelineAction,
  type ContinuousCombatTimeline,type TimelineIntent,
} from "./action-timeline.ts";

/** V2 defensive posture declared BEFORE the impact. Costs one AP and
 * occupies an interval, never one reaction fee per incoming strike. */
export type TimelinePreparedReaction={
 kind:"PREPARE_REACTION";
 defense:"DODGE"|"ENDURE"|"REPEL"|"DEFLECT"|"MAGIC_FIELD"|"COUNTER";
 requestId?:string;
 /** A guess for AoE/ranged magic; only used for DODGE. */
 predictedCenter?:{x:number;y:number};
 /** Physical deflection in degrees; only used for DEFLECT. */
 defenseAngle?:number;
 dodgeDirection?:"TOWARD"|"AWAY";
 counterMagic?:boolean;
};
/** Proactive raised guard for continuous combat. V1 DEFEND is reactive. */
export type TimelineCombatCommand=CombatCommand|TimelinePreparedReaction|{
  kind:"GUARD";weaponSlot:"MAIN_HAND"|"OFF_HAND";requestId?:string;
};

export type CompilationContext={
  /** Resolved only through the approved skills catalog on the server. */
  approvedSkill?:CombatSkillPlan;
  /** The source of a skill strike is not always a physical equipped weapon. */
};

function normal(f:CombatFighter):number{return turnTicks(f);}

function strikeDuration(
 fighter:CombatFighter,params:{
   attackType:"CUT"|"BLUNT"|"PIERCE";usesMagic?:boolean;
   attackSource?: "MAIN_HAND"|"OFF_HAND"|"FIST_RIGHT"|"FIST_LEFT"|"KICK";
   planSkillRange?:number;
 }):number {
 const source:PhysicalAttackSource=params.attackSource??defaultAttackSource(fighter);
 const weapon=weaponForSource(fighter,source);
 const weaponStrike=params.usesMagic!==true&&!!weapon&&
  (params.planSkillRange===undefined||
   params.attackSource==="MAIN_HAND"||params.attackSource==="OFF_HAND");
 return turnTicks(fighter,weaponStrike?params.attackType:undefined);
}

function actionWithOptionalMovement(
 f:CombatFighter,hasMove:boolean,actionTicks:number,
):Pick<TimelineIntent,"durationTicks"|"paCost">{
 return {durationTicks:hasMove?Math.max(normal(f),actionTicks):actionTicks,
   paCost:hasMove?2:1};
}

function blockingEquipment(
 fighter:CombatFighter,slot?:"MAIN_HAND"|"OFF_HAND",
):Pick<TimelineIntent,"blockToolCopyId"|"blockToolSlot">|null {
 const shield=offhandArmorShield(fighter.equippedWearables);
 const picked=slot??(fighter.offhandWeapon||shield?"OFF_HAND":
   fighter.equippedWeapon?"MAIN_HAND":undefined);
 if(!picked)return null; // historical unarmed blocks are a one-time REACT
 const tool=picked==="OFF_HAND"?fighter.offhandWeapon??shield:fighter.equippedWeapon;
 if(!tool)throw new Error("No tienes equipamiento en la mano seleccionada.");
 if(tool.durability!==undefined&&tool.durability<=0)
   throw new Error("No se puede mantener un bloqueo con equipamiento roto.");
 return {blockToolSlot:picked,
   ...(tool.characterItemId!==undefined?{blockToolCopyId:tool.characterItemId}:{})};
}

/** Convert every paid combat action into its *full* nominal tick duration.
 * No action is clipped to the end of the round; a 60-tick blow from tick 95
 * really finishes at tick 155. The supplied ID is generated by the server,
 * not a browser-selected tick or expenditure.
 *
 * Skill/consumable/karma permissions are still validated by the transaction
 * before using this compiler. Passing a skill ID without the trusted plan
 * never authorizes it.
 */
export function compileCombatTimelineIntent(
 snapshot:CombatState,timeline:ContinuousCombatTimeline,by:Side,
 command:TimelineCombatCommand,serverEventId:string,context:CompilationContext={},
):TimelineIntent {
 if(snapshot.status!=="ACTIVE"||timeline.version!==2)
   throw new Error("El combate temporal no está activo.");
 if(by!=="PLAYER"&&by!=="NPC")throw new Error("Combatiente inválido.");
 const actor=snapshot.actors[by];
 if(actor.hp<=0&&command.kind!=="WAIT")
   throw new Error("Un combatiente derrotado solo puede esperar los impactos pendientes.");
 if(command.kind==="ATTACK"||command.kind==="CAST_SKILL"){
   if(command.movementOrder!==undefined&&command.planarMove===undefined)
     throw new Error("Debes trazar un desplazamiento para combinarlo con ataque.");
   if(command.movementOrder!==undefined&&
     !["BEFORE","AFTER"].includes(command.movementOrder))
     throw new Error("Orden de movimiento compuesto inválido.");
   if(command.planarMove!==undefined)validatePlanarMove(command.planarMove);
 }
 const nextAt=Math.max(timeline.nowTick,timeline.actors[by].availableAtTick);
 const base={id:serverEventId,reservedSpeedValue:effectiveCombatSpeed(actor)};
 if(command.kind==="DEFEND"){
   if(!snapshot.pending||snapshot.pending.against!==by)
     throw new Error("Solo puedes defender un impacto destinado a ti.");
   if(command.defense==="NONE")
     return {...base,kind:"WAIT",durationTicks:1,paCost:0};
   const cost=command.planarMove===undefined?1:2;
   if(command.defense==="BLOCK"&&!snapshot.pending.usesMagic&&!snapshot.pending.hybridContact){
     const item=blockingEquipment(actor,command.weaponSlot);
     if(item)return {...base,kind:"BLOCK",durationTicks:Math.max(10,normal(actor)),
       paCost:cost,...item};
   }
   return {...base,kind:"REACT",durationTicks:normal(actor),paCost:cost};
 }
 if(snapshot.pending)
   throw new Error("Resuelve el ataque pendiente antes de iniciar otra acción.");
 switch(command.kind){
  case "PREPARE_REACTION": {
    const reaction=command;
    const keys=Object.keys(reaction);
    if(keys.some(key=>!["kind","defense","requestId","predictedCenter",
      "defenseAngle","dodgeDirection","counterMagic"].includes(key)))
      throw new Error("La reacción anticipada incluye parámetros desconocidos.");
    if(reaction.defense==="DEFLECT"){
      if(!Number.isFinite(reaction.defenseAngle)||reaction.defenseAngle!<0||
         reaction.defenseAngle!>=360||reaction.predictedCenter!==undefined)
        throw new Error("El desvío necesita un ángulo válido, sin adivinación de área.");
    }else if(reaction.defense==="DODGE"){
      const center=reaction.predictedCenter;
      if(!center||!Number.isFinite(center.x)||!Number.isFinite(center.y)||
        center.x<0||center.x>1||center.y<0||center.y>1||
        reaction.defenseAngle!==undefined||
        reaction.counterMagic!==undefined||
        reaction.dodgeDirection!==undefined&&
          !["TOWARD","AWAY"].includes(reaction.dodgeDirection))
        throw new Error("Para esquivar debes marcar una predicción válida.");
    }else if(reaction.defense==="COUNTER"){
      if(reaction.defenseAngle!==undefined||
        reaction.predictedCenter!==undefined||
        reaction.dodgeDirection!==undefined||
        reaction.counterMagic!==undefined&&typeof reaction.counterMagic!=="boolean")
        throw new Error("Contraatacar no admite dibujo ni desplazamiento.");
    }else if(reaction.defenseAngle!==undefined||reaction.predictedCenter!==undefined||
      reaction.dodgeDirection!==undefined||reaction.counterMagic!==undefined){
      throw new Error("Esta reacción no admite trazo ni predicción.");
    }
    if(reaction.defense==="MAGIC_FIELD"&&
      (snapshot.mana?.[by]?.current??0)<1)
      throw new Error("Necesitas al menos un maná para preparar un campo mágico.");
    return {...base,kind:"REACT",durationTicks:normal(actor),
      paCost:reaction.defense==="DODGE"&&reaction.dodgeDirection?2:1};
  }
  case "GUARD": {
    const equipped=blockingEquipment(actor,command.weaponSlot);
    if(!equipped)
      throw new Error("La guardia continua necesita un arma o escudo equipado.");
    return {...base,kind:"BLOCK",durationTicks:Math.max(10,normal(actor)),
      paCost:1,...equipped};
  }
  case "MOVE":
    return {...base,kind:"MOVE",durationTicks:normal(actor),paCost:1};
  case "WAIT":{
    // Waiting relinquishes time through the NEXT 100-tick boundary. No fake
    // 100-tick price is imposed on an actor already at absolute tick 95.
    const remainder=nextAt%100;
    return {...base,kind:"WAIT",durationTicks:100-remainder,paCost:0};
  }
  case "ATTACK": {
    const actionTicks=strikeDuration(actor,{
      attackType:command.attackType,usesMagic:command.usesMagic,
      attackSource:command.attackSource});
    if(command.rangedPhysical===true||command.throwWeapon===true){
      const {flightTicks}=physicalProjectileFlightTicks(snapshot,by,command);
      const rival=by==="PLAYER"?"NPC":"PLAYER";
      return {...base,kind:"ATTACK",durationTicks:actionTicks,
        projectileFlightTicks:flightTicks,
        projectileOrigin:{...fieldPosition(actor)},
        projectileTarget:{...fieldPosition(snapshot.actors[rival])},paCost:1};
    }
    if(command.projectileHeights!==undefined)
      throw new Error("Las alturas de proyectil solo corresponden a un ataque a distancia.");
    return {...base,kind:"ATTACK",
      ...actionWithOptionalMovement(actor,command.planarMove!==undefined,actionTicks)};
  }
  case "CAST_SKILL": {
    const plan=context.approvedSkill;
    if(!plan||plan.id!==command.skillId)
      throw new Error("La habilidad no tiene una aprobación de combate válida.");
    if(plan.category==="OFFENSE"){
      if(!plan.attackType)throw new Error("Habilidad de ataque sin tipo.");
      const from=plan.attackArea?.shape==="SELF_FIELD"?"KICK":command.attackSource;
      const attackTicks=strikeDuration(actor,{attackType:plan.attackType,
        usesMagic:plan.usesMagic,attackSource:from,planSkillRange:plan.rangeMeters});
      return {...base,kind:"SKILL",
        ...actionWithOptionalMovement(actor,command.planarMove!==undefined,attackTicks)};
    }
    if(command.planarMove!==undefined)
      throw new Error("Solo las habilidades ofensivas admiten movimiento compuesto.");
    return {...base,kind:plan.category==="SUMMON"?"SUMMON":"SKILL",
      durationTicks:normal(actor),paCost:1};
  }
  case "COMMAND_SUMMON":
    return {...base,kind:"SUMMON",durationTicks:normal(actor),paCost:1};
  case "USE_ITEM":
    return {...base,kind:"ITEM",durationTicks:normal(actor),paCost:1};
  case "BOOST_KARMA":
    return {...base,kind:"KARMA",durationTicks:normal(actor),paCost:1};
 }
}

/** Authoritative fighter stats set the budgets; client values are ignored. */
export function newTimelineForCombat(snapshot:CombatState):ContinuousCombatTimeline {
 if(snapshot.status!=="ACTIVE")throw new Error("Combate inactivo.");
 return newContinuousCombatTimeline(
   actionPoints(snapshot.actors.PLAYER.constitution),
   actionPoints(snapshot.actors.NPC.constitution),
 );
}

/** Pure pilot integration: reserve a validated command without applying
 * damage, durability or mana. Actual combat only changes when a separate
 * simultaneous batch resolver is installed on the server.
 */
export function reserveCombatTimelineCommand(
 timeline:ContinuousCombatTimeline,snapshot:CombatState,by:Side,
 command:TimelineCombatCommand,serverEventId:string,context:CompilationContext={},
):ContinuousCombatTimeline {
 const intent=compileCombatTimelineIntent(snapshot,timeline,by,command,serverEventId,context);
 return queueTimelineAction(timeline,by,intent);
}
