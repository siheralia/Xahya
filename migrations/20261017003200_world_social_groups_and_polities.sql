-- Social affiliations, cohort fragments, and political entities for Xahya.
CREATE TABLE IF NOT EXISTS public."worldSocialGroup" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  "groupType" text NOT NULL CHECK ("groupType" IN ('CLAN','GUILD','RELIGIOUS','CULTURAL','POLITICAL_MOVEMENT','MIGRANT_COMMUNITY','MILITARY','OTHER')),
  description text,
  status text NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE','DORMANT','DISSOLVED')),
  "leaderCharacterId" integer REFERENCES public."character"(id) ON DELETE SET NULL,
  "foundedAt" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "worldSocialGroup_type_status_idx" ON public."worldSocialGroup" ("groupType", status);
CREATE INDEX IF NOT EXISTS "worldSocialGroup_leader_idx" ON public."worldSocialGroup" ("leaderCharacterId");
CREATE TABLE IF NOT EXISTS public."worldSocialGroupMembership" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "groupId" integer NOT NULL REFERENCES public."worldSocialGroup"(id) ON DELETE CASCADE,
  "cohortId" integer NOT NULL REFERENCES public."populationCohort"(id) ON DELETE CASCADE,
  "memberCount" bigint NOT NULL CHECK ("memberCount" >= 0),
  "wealthShare" bigint NOT NULL DEFAULT 0 CHECK ("wealthShare" >= 0),
  role text NOT NULL DEFAULT 'MEMBER',
  notes text,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "worldSocialGroupMembership_group_cohort_role_key" UNIQUE ("groupId", "cohortId", role)
);
CREATE INDEX IF NOT EXISTS "worldSocialGroupMembership_cohort_idx" ON public."worldSocialGroupMembership" ("cohortId");
CREATE TABLE IF NOT EXISTS public."worldLeaderRelation" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "leaderCharacterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "followerCharacterId" integer NOT NULL REFERENCES public."character"(id) ON DELETE CASCADE,
  "relationType" text NOT NULL DEFAULT 'FOLLOWER',
  loyalty integer NOT NULL DEFAULT 50 CHECK (loyalty BETWEEN 0 AND 100),
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "worldLeaderRelation_unique" UNIQUE ("leaderCharacterId", "followerCharacterId", "relationType"),
  CONSTRAINT "worldLeaderRelation_not_self" CHECK ("leaderCharacterId" <> "followerCharacterId")
);
CREATE INDEX IF NOT EXISTS "worldLeaderRelation_follower_idx" ON public."worldLeaderRelation" ("followerCharacterId");
CREATE TABLE IF NOT EXISTS public."worldPolity" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL UNIQUE,
  "polityType" text NOT NULL DEFAULT 'KINGDOM' CHECK ("polityType" IN ('KINGDOM','CITY_STATE','EMPIRE','REPUBLIC','CONFEDERATION','TRIBE','PRINCIPALITY','OTHER')),
  status text NOT NULL DEFAULT 'PROPOSED' CHECK (status IN ('PROPOSED','ACTIVE','DISPUTED','DISSOLVED')),
  description text,
  "founderCharacterId" integer REFERENCES public."character"(id) ON DELETE SET NULL,
  "foundedAt" timestamptz,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  "updatedAt" timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS "worldPolity_status_type_idx" ON public."worldPolity" (status, "polityType");
CREATE INDEX IF NOT EXISTS "worldPolity_founder_idx" ON public."worldPolity" ("founderCharacterId");
CREATE TABLE IF NOT EXISTS public."worldPolityLocation" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "polityId" integer NOT NULL REFERENCES public."worldPolity"(id) ON DELETE CASCADE,
  "locationId" integer NOT NULL REFERENCES public."worldLocation"(id) ON DELETE CASCADE,
  "relationType" text NOT NULL DEFAULT 'CLAIM' CHECK ("relationType" IN ('CAPITAL','CONTROLS','CLAIM','INFLUENCE')),
  "isCapital" boolean NOT NULL DEFAULT false,
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "worldPolityLocation_unique" UNIQUE ("polityId", "locationId", "relationType")
);
CREATE INDEX IF NOT EXISTS "worldPolityLocation_location_relation_idx" ON public."worldPolityLocation" ("locationId", "relationType");
CREATE TABLE IF NOT EXISTS public."worldPolityGroup" (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "polityId" integer NOT NULL REFERENCES public."worldPolity"(id) ON DELETE CASCADE,
  "groupId" integer NOT NULL REFERENCES public."worldSocialGroup"(id) ON DELETE CASCADE,
  "relationType" text NOT NULL DEFAULT 'SUPPORTS' CHECK ("relationType" IN ('SUPPORTS','MEMBER','OPPOSES','NEUTRAL','SUBJECTS')),
  "createdAt" timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT "worldPolityGroup_unique" UNIQUE ("polityId", "groupId", "relationType")
);
CREATE INDEX IF NOT EXISTS "worldPolityGroup_group_idx" ON public."worldPolityGroup" ("groupId");
